def bh(p):
    p = np.asarray(p, float)
    ok = ~np.isnan(p)
    q = np.full_like(p, np.nan)
    if ok.sum() == 0:
        return q
    o = np.argsort(p[ok]); r = p[ok][o]; n = len(r)
    adj = np.minimum.accumulate((r * n / np.arange(1, n + 1))[::-1])[::-1]
    t = np.empty(n); t[o] = np.minimum(adj, 1)
    q[ok] = t
    return q

