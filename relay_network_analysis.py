# species carrying downstream function, from pathway abundance (species-split rows)
def downstream_carriers(sample, prefixes):
    df = read_humann(sample, "pathabundance")
    pref = df.key.str.split("|").str[0]
    hits = df[pref.apply(lambda x: any(str(x).startswith(p) for p in prefixes))]
    out = {}
    for k, v in zip(hits.key, hits.abund):
        if "|g__" not in k:
            continue
        _, name = species_split(k)
        if name:
            out[name] = out.get(name, 0.0) + float(v)
    return out

