def read_humann(sample, kind):
    f = os.path.join(EXT, f"{sample}_{kind}.tsv")
    df = pd.read_csv(f, sep="\t", comment="#", header=None,
                     names=["key", "abund"])
    df["key"] = df["key"].astype(str)
