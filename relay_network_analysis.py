def species_split(key):
    """Return (genus, 'Genus species') from a HUManN2 species-split key."""
    if "|g__" not in key:
        return None, None
    tail = key.split("|g__", 1)[1]
    if ".s__" in tail:
        g, sp = tail.split(".s__", 1)
        g = g.replace("_", " ").strip()
        sp = sp.replace("_", " ").strip()
        # HUManN2 repeats the genus inside the species field
        if sp.lower().startswith(g.lower()):
            full = sp
        else:
            full = f"{g} {sp}"
    else:
        g = tail.replace("_noname", "").replace("_", " ").strip()
        full = g
    return g, full

